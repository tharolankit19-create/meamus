/**
 * @param {object} spec normalised GameSpec
 * @param {object} [options] packageId / version / author / orientation overrides
 * @returns {{filename:string, buffer:Buffer, files:string[]}}
 */
function buildProject(spec, options = {}) {
  const slug = slugify(spec.gameConfig.title);
  const opts = {
    slug,
    packageId: options.packageId || packageId(spec.gameConfig.title),
    version: options.version || '1.0.0',
    author: options.author || 'meamus',
    authorEmail: options.authorEmail || 'hello@example.com',
    authorUrl: options.authorUrl || 'https://example.com',
    // Puzzle games read better upright; action games default to landscape.
    orientation: options.orientation || (spec.gameConfig.genre === 'puzzle' ? 'portrait' : 'landscape')
  };

  const html = bundler.bundle(spec);

  const files = [
    { name: 'www/index.html', data: html },
    { name: 'config.xml', data: configXml(spec, opts) },
    { name: 'package.json', data: packageJson(spec, opts) },
    { name: 'build.sh', data: buildScript(opts) },
    { name: 'README_APK.md', data: readme(spec, opts) },
    { name: 'res/icon/icon.png', data: PLACEHOLDER_PNG },
    { name: 'gamespec.json', data: JSON.stringify(spec, null, 2) },
    {
      name: '.gitignore',
      data: ['node_modules/', 'platforms/', 'plugins/', 'build.json', '*.keystore', ''].join('\n')
    }
  ];

  return {
    filename: `${slug}-cordova.zip`,
    buffer: zip(files),
    files: files.map((f) => f.name),
    packageId: opts.packageId,
    orientation: opts.orientation
  };
}

module.exports = { buildProject, packageId, slugify };
